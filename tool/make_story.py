"""Builds lib/data/story.dart from tool/story/kafe.txt (episodes start with
'## title', one phrase per line), with syllables counted by espeak-ng.
  python3 tool/make_story.py <sherpa-onnx dir> <piper voice dir>"""
import ctypes, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sherpa, voice = sys.argv[1], sys.argv[2]
ctypes.CDLL(os.path.join(sherpa, 'lib/libonnxruntime.so'), mode=ctypes.RTLD_GLOBAL)
L = ctypes.CDLL(os.path.join(sherpa, 'lib/libsherpa-onnx-c-api.so'))
L.espeak_Initialize(0x02, 0, voice.encode(), 0)
L.espeak_SetVoiceByName(b'fa')
L.espeak_TextToPhonemes.restype = ctypes.c_char_p
V = 'aeiouɑæɒɔəɛɪʊyøœɐ'

def syllables(text):
    text = re.sub('[«»:؛!؟.,،]', ' ', text)
    b = ctypes.c_char_p(text.encode()); p = ctypes.pointer(b); out = []
    while b.value:
        s = L.espeak_TextToPhonemes(p, 1, 0x02)
        if s is None: break
        out.append(s.decode())
    return len(re.findall('[' + V + ']+', ' '.join(out).replace('ː', '')))

eps, cur = [], None
for line in open(os.path.join(root, 'tool/story/kafe.txt'), encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('# '): continue
    if line.startswith('## '):
        cur = {'title': line[3:], 'phrases': []}; eps.append(cur)
    else:
        cur['phrases'].append(line)

def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'")
out = ['// GENERATED by tool/make_story.py from tool/story/kafe.txt. Do not edit.',
       "import 'content.dart';", '',
       "const storyTitle = 'کافه‌ی سر کوچه';", '',
       '/// One episode (about half a page) per day, in order.',
       'const storyEpisodes = <Passage>[']
for i, e in enumerate(eps):
    syl = [syllables(p) for p in e['phrases']]
    out.append('  Passage(')
    out.append(f"    id: 'kafe-{i + 1}',")
    out.append(f"    title: '{esc(e['title'])}',")
    out.append("    source: 'کافه‌ی سر کوچه',")
    out.append("    audience: 'all',")
    out.append('    phrases: [')
    for p in e['phrases']: out.append(f"      '{esc(p)}',")
    out.append('    ],')
    out.append(f'    syllables: {syl},')
    out.append('  ),')
out.append('];')
open(os.path.join(root, 'lib/data/story.dart'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(eps), 'episodes,', sum(len(e['phrases']) for e in eps), 'phrases')
