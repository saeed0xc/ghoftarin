"""Builds lib/data/word_bank.dart from tool/words/*.txt, counting syllables
with espeak-ng (through the sherpa-onnx library). Usage:
  python3 tool/make_words.py <sherpa-onnx dir> <piper voice dir>"""
import ctypes, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sherpa, voice = sys.argv[1], sys.argv[2]
ctypes.CDLL(os.path.join(sherpa, 'lib/libonnxruntime.so'), mode=ctypes.RTLD_GLOBAL)
L = ctypes.CDLL(os.path.join(sherpa, 'lib/libsherpa-onnx-c-api.so'))
L.espeak_Initialize(0x02, 0, voice.encode(), 0)
L.espeak_SetVoiceByName(b'fa')
L.espeak_TextToPhonemes.restype = ctypes.c_char_p
V = 'aeiouɑæɒɔəɛɪʊyøœɐ'

def syllables(text):
    b = ctypes.c_char_p(text.encode()); p = ctypes.pointer(b); out = []
    while b.value:
        s = L.espeak_TextToPhonemes(p, 1, 0x02)
        if s is None: break
        out.append(s.decode())
    return len(re.findall('[' + V + ']+', ' '.join(out).replace('ː', '')))

def klass(w):
    c = w[0]
    if c in 'اآعهحئ': return 0  # vowel or h: easiest soft start
    if c in 'سصثشفزذضظژخغویلرمن': return 1  # continuants
    return 2  # plosives and affricates: p b t d k g q j ch

def read(name):
    txt = open(os.path.join(root, 'tool/words', name), encoding='utf-8').read()
    return [l for l in txt.splitlines() if l.strip() and not l.startswith('#')]

skip = {'هر', 'هیچ', 'همه', 'هوای', 'نه'}
words, seen = [], set()
for f in ('everyday.txt', 'more.txt'):
    for line in read(f):
        for w in line.split():
            if w in seen or w in skip or not re.fullmatch('[؀-ۿ‌]+', w): continue
            seen.add(w); words.append(w)
phrases = [l.strip() for l in read('phrases.txt')]

def esc(s): return s.replace("'", "\\'")
out = ['// GENERATED by tool/make_words.py from tool/words/*.txt. Do not edit.',
       '// Syllables counted with espeak-ng (an unwritten ezafe may be missed).',
       "import 'word_lessons.dart';", '', 'const wordBank = <BankWord>[']
for w in words:
    out.append(f"  BankWord('{esc(w)}', {max(1, syllables(w))}, {klass(w)}),")
out += ['];', '', 'const phraseBank = <BankWord>[']
for p in phrases:
    out.append(f"  BankWord('{esc(p)}', {max(1, syllables(p))}, {klass(p)}),")
out.append('];')
open(os.path.join(root, 'lib/data/word_bank.dart'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
from collections import Counter
print(len(words), 'words,', len(phrases), 'phrases')
print('by class', Counter(klass(w) for w in words))
print('by syllables', sorted(Counter(min(5, syllables(w)) for w in words).items()))
