"""Builds lib/data/partner_scenes.dart and assets/partner/<id>-<n>.mp3 from
tool/partner/scenes.txt with offline Persian TTS (sherpa-onnx + Piper).
  python3 tool/make_partner.py <sherpa-onnx dir> <voice dir> [<voice dir 2>]"""
import os, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sherpa, voices = sys.argv[1], sys.argv[2:]
scenes, cur = [], None
for line in open(os.path.join(root, 'tool/partner/scenes.txt'), encoding='utf-8'):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('# '): continue
    if line.startswith('## '):
        sid, title, level, role = [x.strip() for x in line[3:].split('|')]
        cur = {'id': sid, 'title': title, 'level': int(level), 'role': role, 'turns': []}
        scenes.append(cur)
    elif line.startswith('P:'):
        cur['turns'].append({'p': line[2:].strip(), 'h': ''})
    elif line.startswith('H:'):
        cur['turns'][-1]['h'] = line[2:].strip()

def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'")
out = ['// GENERATED by tool/make_partner.py from tool/partner/scenes.txt.',
       "import 'partner.dart';", '', 'const partnerScenes = <Scene>[']
for s in scenes:
    out.append(f"  Scene('{s['id']}', '{esc(s['title'])}', {s['level']}, '{esc(s['role'])}', [")
    for t in s['turns']:
        out.append(f"    Turn('{esc(t['p'])}', '{esc(t['h'])}'),")
    out.append('  ]),')
out.append('];')
open(os.path.join(root, 'lib/data/partner_scenes.dart'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')

dst = os.path.join(root, 'assets/partner'); os.makedirs(dst, exist_ok=True)
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(sherpa, 'lib'))
for k, s in enumerate(scenes):
    voice = voices[k % len(voices)]
    model = next(f for f in os.listdir(voice) if f.endswith('.onnx'))
    for i, t in enumerate(s['turns']):
        with tempfile.TemporaryDirectory() as tmp:
            wav = os.path.join(tmp, 'a.wav')
            subprocess.run([os.path.join(sherpa, 'bin/sherpa-onnx-offline-tts'),
                            f'--vits-model={os.path.join(voice, model)}',
                            f'--vits-tokens={os.path.join(voice, "tokens.txt")}',
                            f'--vits-data-dir={os.path.join(voice, "espeak-ng-data")}',
                            '--vits-length-scale=1.05',
                            f'--output-filename={wav}', t['p']], check=True, env=env, capture_output=True)
            subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav,
                            '-af', 'adelay=100,loudnorm=I=-18:TP=-2,aresample=22050',
                            '-ac', '1', '-b:a', '40k', os.path.join(dst, f"{s['id']}-{i}.mp3")], check=True)
print(len(scenes), 'scenes,', sum(len(s['turns']) for s in scenes), 'lines')
